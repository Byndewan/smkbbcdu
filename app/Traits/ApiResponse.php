<?php

namespace App\Traits;

trait ApiResponse
{
    /**
     * Response Sukses
     */
    protected function success($data, $message = null, $code = 200)
    {
        return response()->json([
            'status' => 'success',
            'message' => $message,
            'data' => $data
        ], $code);
    }

    /**
     * Response Gagal / Error
     */
    protected function error($message, $code, $data = null)
    {
        return response()->json([
            'status' => 'error',
            'message' => $message,
            'data' => $data
        ], $code);
    }
}
